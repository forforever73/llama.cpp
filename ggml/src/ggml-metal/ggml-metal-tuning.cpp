// Compile-time: every tuned-table row must be a family member or the baseline.
static constexpr bool mm_tile_cfg_in_family(int16_t nr0, int16_t nr1) {
    if (nr0 == MM_TILE_BASELINE_CFG.nr0 && nr1 == MM_TILE_BASELINE_CFG.nr1) { return true; }
    for (const auto & f : MM_TILE_FAMILY) {
        if (f.nr0 == nr0 && f.nr1 == nr1) { return true; }
    }
    return false;
}

static constexpr bool mm_tile_table_all_legal() {
    for (const auto & e : mm_tile_tuned_table) {
        if (!mm_tile_cfg_in_family(e.cfg.nr0, e.cfg.nr1)) { return false; }
    }
    return true;
}

static_assert(mm_tile_table_all_legal(), "mm_tile_tuned_table row uses an illegal (nr0,nr1)");

// Map a device SKU to its Apple GPU family, then to that family's representative
// SKU (the one we have tuned data for). Apple GPU family is a static property of
// the SKU: M1->Apple7, M2->Apple8, M3/M4/M5->Apple9. Used as the device-level
// fallback when the exact device_id has no tuned rows.
static int mm_tile_gpu_family(enum ggml_metal_device_id device_id) {
    switch (device_id) {
        case GGML_METAL_DEVICE_M1:
        case GGML_METAL_DEVICE_M1_PRO:
        case GGML_METAL_DEVICE_M1_MAX:
        case GGML_METAL_DEVICE_M1_ULTRA:
            return 7;
        case GGML_METAL_DEVICE_M2:
        case GGML_METAL_DEVICE_M2_PRO:
        case GGML_METAL_DEVICE_M2_MAX:
        case GGML_METAL_DEVICE_M2_ULTRA:
            return 8;
        case GGML_METAL_DEVICE_M3:
        case GGML_METAL_DEVICE_M3_PRO:
        case GGML_METAL_DEVICE_M3_MAX:
        case GGML_METAL_DEVICE_M3_ULTRA:
        case GGML_METAL_DEVICE_M4:
        case GGML_METAL_DEVICE_M4_PRO:
        case GGML_METAL_DEVICE_M4_MAX:
        case GGML_METAL_DEVICE_M5:
        case GGML_METAL_DEVICE_M5_PRO:
        case GGML_METAL_DEVICE_M5_MAX:
        case GGML_METAL_DEVICE_M5_ULTRA:
            return 9;
        default:
            return 0;
    }
}

static enum ggml_metal_device_id mm_tile_family_representative(enum ggml_metal_device_id device_id) {
    switch (mm_tile_gpu_family(device_id)) {
        case 9:  return GGML_METAL_DEVICE_M4_MAX;  // only Apple9 has tuned data
        default: return GGML_METAL_DEVICE_GENERIC;
    }
}

static bool         g_mm_override_set = false;
static mm_tile_cfg_t g_mm_override_cfg = { 64, 32 };

void mm_tile_set_override(mm_tile_cfg_t cfg) {
    g_mm_override_cfg = cfg;
    g_mm_override_set = true;
}

void mm_tile_clear_override() {
    g_mm_override_set = false;
}

bool mm_tile_override_active() {
    return g_mm_override_set;
}

static const mm_tile_cfg_t * find_cfg(const mm_tile_entry_t * tbl, size_t n, const mm_tile_key_t & k) {
    for (size_t i = 0; i < n; ++i) {
        if (memcmp(&tbl[i].key, &k, sizeof(k)) == 0) { return &tbl[i].cfg; }
    }
    return nullptr;
}

// Core lattice lookup against an explicit table. mm_tile_pick and the self-test
// share this so both exercise the same collapse logic. Folding order is weakest
// signal first and tokens is never folded:
//   L1 exact  (N0_b, tokens_b)
//   L2        (ANY,  tokens_b)   out-feat missing, keep tokens
//   L3        baseline (64x32)   nothing matched
// The device axis wraps the lattice: exact device_id -> family rep (t<32 rows
// only, see below) -> baseline.
static mm_tile_cfg_t mm_tile_pick_from_table(const mm_tile_entry_t * tbl, size_t n,
                                             enum ggml_metal_device_id device_id,
                                             int dtype, int64_t N_out, int64_t tokens) {
    const int N0_b     = mm_tile_N0_bucket(N_out);
    const int tokens_b = mm_tile_token_bucket(tokens);

    mm_tile_key_t k{};
    k.dtype    = (int8_t) dtype;
    k.tokens_b = (int8_t) tokens_b;  // never collapsed; set once

    auto lookup = [&](enum ggml_metal_device_id dev) -> const mm_tile_cfg_t * {
        k.device_id = (int8_t) dev;
        k.N0_b = (int8_t) N0_b;                                  // L1
        if (auto * c = find_cfg(tbl, n, k)) { return c; }
        k.N0_b = MM_TILE_BUCKET_ANY;                             // L2
        return find_cfg(tbl, n, k);
    };

    // exact device_id -> family representative SKU -> baseline
    if (auto * c = lookup(device_id)) { return *c; }

    // Family inheritance is token-gated: tokens < 32 rows transfer across SKUs
    // because their wins come from baseline's token padding + bc_out slow path,
    // which are kernel-structural and device-independent. tokens >= 32 rows encode
    // occupancy crossovers that scale with GPU core count, so they only apply on
    // the exact device they were tuned on; an untuned sibling SKU falls through to
    // baseline there (forfeits the win, cannot regress).
    if (tokens_b <= 1) {
        const enum ggml_metal_device_id rep = mm_tile_family_representative(device_id);
        if (rep != GGML_METAL_DEVICE_GENERIC && rep != device_id) {
            if (auto * c = lookup(rep)) { return *c; }
        }
    }
    return mm_tile_baseline_cfg();  // L3
}

mm_tile_cfg_t mm_tile_pick(enum ggml_metal_device_id device_id,
                            int dtype,
                            int64_t N_out,
                            int64_t tokens) {
    if (g_mm_override_set) { return g_mm_override_cfg; }

    // Large-batch short-circuit: every tuned device converged to baseline for
    // tokens >= 256 (no tuned row serves that range), and at these sizes the
    // baseline dispatch always saturates the GPU. Skip the scan.
    if (tokens >= 256) { return mm_tile_baseline_cfg(); }

    const mm_tile_cfg_t cfg = mm_tile_pick_from_table(mm_tile_tuned_table, std::size(mm_tile_tuned_table),
                                                      device_id, dtype, N_out, tokens);

    // Occupancy veto (see MM_TILE_C_SAT_M4_MAX): if the baseline dispatch
    // already saturates the GPU, a smaller tile cannot win, so override any
    // small-tile row back to baseline. Guards against table extrapolation on
    // unsampled shapes. tokens < 32 wins are padding-driven, not occupancy
    // -driven, and stay exempt.
    if (tokens >= 32 &&
        (cfg.nr0 != MM_TILE_BASELINE_CFG.nr0 || cfg.nr1 != MM_TILE_BASELINE_CFG.nr1)) {
        const int64_t n_tg = ((N_out + 63) / 64) * ((tokens + 31) / 32);
        if (n_tg >= MM_TILE_C_SAT_M4_MAX) {
            return mm_tile_baseline_cfg();
        }
    }
    return cfg;
}

static int g_mm_ne11_override = -1;

int mm_tile_ne11_mm_min(enum ggml_metal_device_id device_id, int dtype, int64_t N_out) {
    // Clamp to the default: may only lower the boundary (ne11>8 in mv_ext aborts).
    if (g_mm_ne11_override >= 0) {
        return g_mm_ne11_override < MM_TILE_NE11_MM_MIN_DEFAULT ? g_mm_ne11_override : MM_TILE_NE11_MM_MIN_DEFAULT;
    }
    const int N0_b = mm_tile_N0_bucket(N_out);
    for (const auto & e : mm_tile_ne11_mm_min_table) {
        if (e.device_id == (int8_t) device_id && e.dtype == (int8_t) dtype && e.N0_b == (int8_t) N0_b) {
            return e.ne11_mm_min < MM_TILE_NE11_MM_MIN_DEFAULT ? e.ne11_mm_min : MM_TILE_NE11_MM_MIN_DEFAULT;
        }
    }
    return MM_TILE_NE11_MM_MIN_DEFAULT;
}

// tune-only; not thread-safe (matches mm_tile_set_override). Never set in production.
void mm_tile_set_ne11_mm_min_override(int ne11_mm_min) {
    g_mm_ne11_override = ne11_mm_min;
}

int mm_tile_lattice_selftest() {
    // Synthetic table keyed to one device; queries from that device isolate the
    // N0_b collapse, queries from a sibling SKU exercise the token-gated family
    // inheritance. Queries land in the buckets noted inline.
    constexpr enum ggml_metal_device_id dev = GGML_METAL_DEVICE_M4_MAX;
    constexpr enum ggml_metal_device_id sib = GGML_METAL_DEVICE_M4_PRO;  // same family rep (M4_MAX)
    constexpr int                       dt  = GGML_TYPE_Q4_0;
    constexpr mm_tile_cfg_t exact_cfg = { 128, 32 };
    constexpr mm_tile_cfg_t l2_cfg    = {  32,  8 };
    constexpr mm_tile_cfg_t tok0_cfg  = {  32, 16 };
    constexpr mm_tile_cfg_t tok1_cfg  = {  64,  8 };
    const mm_tile_entry_t tbl[] = {
        { { dev, dt, 1, 2, {0,0,0,0} }, exact_cfg },  // L1: N0_b=1, tokens_b=2
        { { dev, dt, MM_TILE_BUCKET_ANY, 2, {0,0,0,0} }, l2_cfg },  // L2: tokens_b=2
        { { dev, dt, 1, 0, {0,0,0,0} }, tok0_cfg },   // L1: N0_b=1, tokens_b=0
        { { dev, dt, 1, 1, {0,0,0,0} }, tok1_cfg },   // L1: N0_b=1, tokens_b=1
    };
    const size_t        n    = std::size(tbl);
    const mm_tile_cfg_t base = mm_tile_baseline_cfg();

    auto eq = [](mm_tile_cfg_t a, mm_tile_cfg_t b) { return a.nr0 == b.nr0 && a.nr1 == b.nr1; };
    // Bucket edges: N0_b {2048,4608,8192,30000}, tokens_b {9,32,64,128}.
    int fails = 0;
    // L1 hit: N0_b=1 (4096), tokens_b=2 (48)
    if (!eq(mm_tile_pick_from_table(tbl, n, dev, dt, 4096, 48), exact_cfg)) { fails++; }
    // L1 miss, L2 hit: N0_b=0 (512, no exact row), tokens_b=2 (48)
    if (!eq(mm_tile_pick_from_table(tbl, n, dev, dt,  512, 48), l2_cfg))    { fails++; }
    // all miss -> baseline: tokens_b=0 (8) matches no row at N0_b=0
    if (!eq(mm_tile_pick_from_table(tbl, n, dev, dt,  512,  8), base))      { fails++; }
    // tokens never folds: N0_b=1 would hit L1 if tokens folded, but
    // tokens_b=4 (256) matches no row at any level -> baseline
    if (!eq(mm_tile_pick_from_table(tbl, n, dev, dt, 4096, 256), base))     { fails++; }
    // the edge at 9 separates the routed small-batch range from the rest: 8 and 16
    // sit in different buckets and must each get their own row
    if (!eq(mm_tile_pick_from_table(tbl, n, dev, dt, 4096,   8), tok0_cfg)) { fails++; }
    if (!eq(mm_tile_pick_from_table(tbl, n, dev, dt, 4096,  16), tok1_cfg)) { fails++; }
    // family inheritance, tokens < 32: sibling SKU inherits both low buckets
    if (!eq(mm_tile_pick_from_table(tbl, n, sib, dt, 4096,   8), tok0_cfg)) { fails++; }
    if (!eq(mm_tile_pick_from_table(tbl, n, sib, dt, 4096,  16), tok1_cfg)) { fails++; }
    // family inheritance is token-gated: sibling SKU must NOT inherit tokens >= 32
    // rows (occupancy-dependent) -> baseline despite the rep's L1/L2 rows
    if (!eq(mm_tile_pick_from_table(tbl, n, sib, dt, 4096,  48), base))     { fails++; }
    return fails;
}

