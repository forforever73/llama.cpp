int mm_tile_N0_bucket(int64_t N_out) {
    for (int i = 0; i < (int) std::size(MM_TILE_N0_BUCKETS); ++i) {
        if (N_out < MM_TILE_N0_BUCKETS[i]) { return i; }
    }
    return (int) std::size(MM_TILE_N0_BUCKETS);
}

int mm_tile_token_bucket(int64_t tokens) {
    for (int i = 0; i < (int) std::size(MM_TILE_TOKEN_BUCKETS); ++i) {
        if (tokens < MM_TILE_TOKEN_BUCKETS[i]) { return i; }
    }
    return (int) std::size(MM_TILE_TOKEN_BUCKETS);
}

mm_tile_cfg_t mm_tile_baseline_cfg() {
    return MM_TILE_BASELINE_CFG;
}

// Per-device/(dtype, N0-bucket) mv_ext->mm break-even, measured by the sweep (the
// token-bucket-0 tile's pick vs mv_ext at ne11 in [2,8]). Rows only route small
// batches into the tile where measured faster, so the two tables are regenerated
// together: lowering the boundary is only safe against the tile that bucket 0
// actually serves. Bucket 0 (N0<2048) never appears (mv_ext wins at narrow
// output). Exact device only.
